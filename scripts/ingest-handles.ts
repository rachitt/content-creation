import "dotenv/config";
import fs from "node:fs/promises";
import path from "node:path";

type ScrapedPost = {
  body: string;
  platform: "linkedin" | "x";
};

async function main() {
  const linkedinHandle = process.env.OWN_LINKEDIN_HANDLE;
  const xHandle = process.env.OWN_X_HANDLE;
  const posts = await scrapeOwnedPosts(linkedinHandle, xHandle);
  const summary = distillVoiceSamples(posts);
  const target = path.resolve(process.cwd(), "src/content/brand/voice-samples.md");

  await fs.writeFile(target, summary, "utf8");
  console.log(`[ingest:handles] wrote ${target}`);
}

