function distillVoiceSamples(posts: ScrapedPost[]): string {
  const recent = posts.slice(-50);
  const linkedin = recent.filter((post) => post.platform === "linkedin");
  const x = recent.filter((post) => post.platform === "x");

  return [
    "# Voice Samples",
    "",
    "> Generated by `pnpm ingest:handles` from the last 50 owned posts. Hand-written seed samples remain below until Slice A scraping is available.",
    "",
    "## Mined Summary",
    "",
    `Posts analyzed: ${recent.length}`,
    "",
    "### Themes",
    summarizeThemes(recent),
    "",
    "### Opener Patterns",
    summarizeOpeners(recent),
    "",
    "### CTA Patterns",
    summarizeCtas(recent),
    "",
    "## Source Counts",
    "",
    `- LinkedIn: ${linkedin.length}`,
    `- X: ${x.length}`,
    "",
    "## Hand-Written LinkedIn Samples",
    "",
    fallbackLinkedInSamples(),
    "",
    "## Hand-Written X Samples",
    "",
    fallbackXSamples(),
  ].join("\n");
}

function summarizeThemes(posts: ScrapedPost[]): string {
  if (posts.length === 0) return "- No owned posts available yet.";
  const keywords = ["AI", "workflow", "prototype", "rebuild", "handoff", "audit", "MVP", "integration"];
  return keywords
    .map((keyword) => ({
      keyword,
      count: posts.filter((post) => post.body.toLowerCase().includes(keyword.toLowerCase())).length,
    }))
    .filter((item) => item.count > 0)
    .sort((a, b) => b.count - a.count)
    .map((item) => `- ${item.keyword}: ${item.count} mentions`)
    .join("\n") || "- No repeated themes detected.";
}

function summarizeOpeners(posts: ScrapedPost[]): string {
  const openers = posts
    .map((post) => post.body.split(/\r?\n/).find((line) => line.trim().length > 0)?.trim())
    .filter((line): line is string => Boolean(line))
    .slice(0, 10);
  return openers.length ? openers.map((line) => `- ${line}`).join("\n") : "- No opener patterns available yet.";
}

function summarizeCtas(posts: ScrapedPost[]): string {
  const ctas = posts
    .map((post) => post.body.split(/\r?\n/).reverse().find((line) => line.trim().length > 0)?.trim())
    .filter((line): line is string => Boolean(line))
    .filter((line) => /dm|send|reply|call|audit|link|tell me/i.test(line))
    .slice(0, 10);
  return ctas.length ? ctas.map((line) => `- ${line}`).join("\n") : "- No CTA patterns available yet.";
}

